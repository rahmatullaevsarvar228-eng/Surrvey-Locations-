def md(text: str) -> str:
    """**bold** and `code` -> reportlab markup."""
    t = escape(text)
    out, bold = [], False
    for i, part in enumerate(t.split("**")):
        out.append(("<b>" if i % 2 else "") + part + ("</b>" if i % 2 else ""))
    t = "".join(out)
    parts = t.split("`")
    t = "".join(p if i % 2 == 0 else f'<font face="DV-B" color="#1F4E79">{p}</font>' for i, p in enumerate(parts))
    return t


class Doc(SimpleDocTemplate):
    def afterFlowable(self, f):
        if isinstance(f, Paragraph) and f.style.name in ("h1", "h2"):
            level = 0 if f.style.name == "h1" else 1
            key = f"h{id(f)}"
            self.canv.bookmarkPage(key)
            self.canv.addOutlineEntry(f.getPlainText(), key, level=level, closed=level > 0)
            self.notify("TOCEntry", (level, f.getPlainText(), self.page, key))


story = []


def h1(t):
    story.append(PageBreak())
    story.append(Paragraph(md(t), S["h1"]))


def h2(t):
    story.append(Paragraph(md(t), S["h2"]))


def p(*ts):
    for t in ts:
        story.append(Paragraph(md(t), S["body"]))


def bullets(items, numbered=False):
    for i, t in enumerate(items, 1):
        mark = f"{i}." if numbered else "•"
        story.append(Paragraph(md(t), ParagraphStyle("li", parent=S["body"], leftIndent=16, bulletIndent=3,
                                                     spaceAfter=3), bulletText=mark))
    story.append(Spacer(1, 3))


def box(t, kind="note"):
    color = {"note": "#E8EDF3", "tip": "#E3F1E6", "warn": "#FBF0D0"}[kind]
    label = {"note": "Важно", "tip": "Совет", "warn": "Внимание"}[kind]
    tb = Table([[Paragraph(f"<b>{label}.</b> " + md(t), S["body"])]], colWidths=[W])
    tb.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(color)),
                            ("LEFTPADDING", (0, 0), (-1, -1), 9), ("RIGHTPADDING", (0, 0), (-1, -1), 9),
                            ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]))
    story.append(tb)
    story.append(Spacer(1, 7))


def table(rows, widths, header=True):
    data = [[Paragraph(md(str(c)), S["cellb"] if (header and r == 0) else S["cell"]) for c in row]
            for r, row in enumerate(rows)]
    tb = Table(data, colWidths=[w * mm for w in widths], repeatRows=1 if header else 0)
    st = [("GRID", (0, 0), (-1, -1), 0.4, LINE), ("VALIGN", (0, 0), (-1, -1), "TOP"),
          ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]
    if header:
        st.append(("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E8EDF3")))
    tb.setStyle(TableStyle(st))
    story.append(tb)
    story.append(Spacer(1, 8))


def img(name, caption, width=W):
    path = SHOTS / name
    if not path.exists():
        return
    from reportlab.lib.utils import ImageReader
    iw, ih = ImageReader(str(path)).getSize()
    h = width * ih / iw
    if h > 150 * mm:
        width, h = width * 150 * mm / h, 150 * mm
    im = Image(str(path), width=width, height=h)
    frame = Table([[im]], colWidths=[width + 2])
    frame.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.6, LINE), ("LEFTPADDING", (0, 0), (-1, -1), 0),
                               ("RIGHTPADDING", (0, 0), (-1, -1), 0), ("TOPPADDING", (0, 0), (-1, -1), 0),
                               ("BOTTOMPADDING", (0, 0), (-1, -1), 0)]))
    story.append(KeepTogether([frame, Paragraph(md(caption), S["cap"])]))


